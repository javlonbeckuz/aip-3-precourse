import { launch, URL } from './cdp_fe.mjs';
const W = +process.argv[2] || 390, H = W > 600 ? 878 : 844;
const b = await launch(W, H, W < 600);
await b.goto(URL + '?solo&view=gate');
const state = () => b.ev(`JSON.stringify({help:document.getElementById('gid-h').textContent,err:document.getElementById('gid-h').classList.contains('err'),val:document.getElementById('gid').value,view:document.body.dataset.view,ldr:!document.getElementById('gate-loader').hidden,btnY:Math.round(document.querySelector('.mx-btn').getBoundingClientRect().top),formY:Math.round(document.querySelector('.mx').getBoundingClientRect().top),maxlen:document.getElementById('gid').maxLength})`);
const out = [];
out.push(['initial', await state()]);
const setv = async v => { await b.ev(`(()=>{const g=document.getElementById('gid');g.value='';g.focus()})()`); await b.type(v); await b.wait(150); };
const paste = async t => { await b.ev(`(()=>{const g=document.getElementById('gid');g.value='';g.focus();const dt=new DataTransfer();dt.setData('text',${JSON.stringify(t)});g.dispatchEvent(new ClipboardEvent('paste',{clipboardData:dt,cancelable:true,bubbles:true}))})()`); await b.wait(150); };
await setv('7KQ2X0'); out.push(['type 7KQ2X0 (invalid)', await state()]); await b.shot('g_err_invalid_' + W);
await setv('7KQ2'); await b.click('.mx-btn'); await b.wait(100); out.push(['7KQ2 + Kirish (short)', await state()]); await b.shot('g_err_short_' + W);
await setv('KKKKKK'); out.push(['KKKKKK (not found)', await state()]); await b.shot('g_err_notfound_' + W);
await setv('AIP-7K'); out.push(['type AIP-7K', await state()]);
await paste('AIP-7KQ2X0'); out.push(['paste AIP-7KQ2X0', await state()]);
await paste('  aip-7kq2 '); out.push(['paste "  aip-7kq2 "', await state()]);
await setv('AIP7KQ2XM'); await b.wait(400); out.push(['type AIP7KQ2XM', await state()]);
await b.wait(2200); out.push(['after login', await state()]);
for (const [k, v] of out) console.log(k.padEnd(28), v);
console.log('logs', JSON.stringify(b.logs));
b.close();
