#!/usr/bin/env python3
"""Build deck/assets/talk_data.js from talking-track.md.

Each "## N · time · title" section of the talking track becomes the talk text
of slide N (1-based), shown in the deck's notes drawer (P key).
Fails if a slide has no section, a section names a slide that does not exist,
or the file contains an em dash.
Usage: python3 _build/build_talk.py   (paths resolve from this file)
"""
import json
import re
import sys
from pathlib import Path

DAY = Path(__file__).resolve().parent.parent
SRC = DAY / "talking-track.md"
OUT = DAY / "deck" / "assets" / "talk_data.js"
SLIDES = DAY / "deck" / "assets" / "slides_data.js"
WPM = 105  # spoken Uzbek, with pauses


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    if chr(0x2014) in text:
        print("FAIL: em dash in talking-track.md")
        return 1
    n_slides = len(re.findall(r"\blayout:\s*'", SLIDES.read_text(encoding="utf-8")))
    parts = re.split(r"^## (\d+) · ([^\n]*)\n", text, flags=re.M)
    talk, rows = {}, []
    for i in range(1, len(parts), 3):
        num, head, body = int(parts[i]), parts[i + 1].strip(), parts[i + 2].strip()
        if num in talk:
            print(f"FAIL: slide {num} appears twice")
            return 1
        talk[num] = body
        spoken = [ln for ln in body.splitlines() if ln.strip() and not ln.lstrip().startswith("[")]
        words = sum(len(ln.split()) for ln in spoken)
        rows.append((num, head, words))
    missing = [n for n in range(1, n_slides + 1) if n not in talk]
    extra = [n for n in talk if n < 1 or n > n_slides]
    if missing or extra:
        print(f"FAIL: deck has {n_slides} slides; missing sections {missing}, unknown sections {extra}")
        return 1
    OUT.write_text(
        "/* Generated by _build/build_talk.py from talking-track.md. Do not edit by hand. */\n"
        "window.TALK_DATA = " + json.dumps(talk, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    total = 0
    for num, head, words in rows:
        total += words
        print(f"{num:>2}  {words:>4} so'z  {words / WPM:>4.1f} daq  {head}")
    print(f"Jami: {total} so'z, taxminan {total / WPM:.0f} daqiqa gap ({WPM} so'z/daq). {len(talk)} slayd -> {OUT.relative_to(DAY)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
