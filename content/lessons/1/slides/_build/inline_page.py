"""Make a single self-contained HTML file from a Day 1 page: inline its stylesheets (with fonts as data URIs)
and its local scripts, so the file can be sent through Telegram and opened offline.

Run:  python3 day-1/_build/inline_page.py              (builds every pair in JOBS)
Paths resolve relative to this file.
"""
import base64
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
DAY1 = HERE.parent
JOBS = [
    ("demos/tokenizer/index.html", "demos/tokenizer/tokenizer-offline.html"),
]
MIME = {".woff2": "font/woff2", ".woff": "font/woff", ".ttf": "font/ttf", ".png": "image/png", ".svg": "image/svg+xml"}


def inline_css(css_path: pathlib.Path) -> str:
    css = css_path.read_text(encoding="utf-8")

    def repl(m):
        ref = m.group(1).strip("'\"")
        if ref.startswith(("data:", "http")):
            return m.group(0)
        f = (css_path.parent / ref).resolve()
        data = base64.b64encode(f.read_bytes()).decode()
        return f"url('data:{MIME.get(f.suffix, 'application/octet-stream')};base64,{data}')"

    return re.sub(r"url\(([^)]+)\)", repl, css)


def build(src_rel: str, out_rel: str):
    src = DAY1 / src_rel
    html = src.read_text(encoding="utf-8")

    def link(m):
        href = m.group(1)
        return "<style>\n" + inline_css((src.parent / href).resolve()) + "\n</style>"

    def script(m):
        js = (src.parent / m.group(1)).resolve().read_text(encoding="utf-8")
        return "<script>\n" + js.replace("</script", "<\\/script") + "\n</script>"

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', link, html)
    html = re.sub(r'<script src="([^"]+)"></script>', script, html)
    html = html.replace("<title>", "<!-- Single-file build of " + src_rel + " (generated by day-1/_build/inline_page.py; edit the source, not this file). -->\n<title>", 1)
    out = DAY1 / out_rel
    out.write_text(html, encoding="utf-8")
    print(f"{out_rel}: {out.stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    for s, o in JOBS:
        build(s, o)
