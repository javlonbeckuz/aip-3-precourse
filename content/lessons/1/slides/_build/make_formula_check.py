"""Generate the hallucination demo file: a small October sales sheet with two realistic traps, plus its answer key.

Run:  uv run --with openpyxl python3 day-1/_build/make_formula_check.py
Writes (relative to this file): ../demos/formula-check/savdo-oktabr.xlsx, savdo-oktabr.csv, javob-kaliti.md, data.js (for index.html)
Traps: (1) three amounts were pasted from Telegram as text ("1 250 000"), so Excel's SUM skips them;
       (2) the last row is dated 1 November, outside October.
Deterministic: same seed, same file.
"""
import csv
import json
import datetime
import pathlib
import random

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "demos" / "formula-check"

PRODUCTS = [
    ("Daftar, 96 varaq", 9000),
    ("Ruchka, ko‘k", 3000),
    ("Kalkulyator", 85000),
    ("A4 qog‘oz, 500 varaq", 62000),
    ("Papka-registrator", 28000),
    ("Marker to‘plami", 45000),
    ("Stepler", 38000),
]
TEXT_ROWS = {6, 17, 29}  # 1-based data rows whose amount is stored as text


def money_text(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def main():
    rnd = random.Random(2611)
    rows = []
    for i in range(34):
        day = 1 + (i * 31) // 34
        name, price = PRODUCTS[rnd.randrange(len(PRODUCTS))]
        qty = rnd.choice([2, 3, 5, 6, 10, 12, 20, 24, 30])
        rows.append({"date": datetime.date(2026, 10, day), "name": name, "qty": qty, "price": price,
                     "sum": qty * price, "kassa": f"Kassa {1 + rnd.randrange(2)}"})
    name, price = PRODUCTS[3]
    rows.append({"date": datetime.date(2026, 11, 1), "name": name, "qty": 40, "price": price, "sum": 40 * price, "kassa": "Kassa 1"})

    true_oct = sum(r["sum"] for r in rows if r["date"].month == 10)
    text_sum = sum(r["sum"] for i, r in enumerate(rows, 1) if i in TEXT_ROWS)
    nov = sum(r["sum"] for r in rows if r["date"].month == 11)
    excel_sum_all = sum(r["sum"] for i, r in enumerate(rows, 1) if i not in TEXT_ROWS)
    excel_sum_oct = excel_sum_all - nov

    OUT.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    ws = wb.active
    ws.title = "Oktabr"
    head = ["Sana", "Mahsulot", "Miqdor", "Narx, so‘m", "Summa, so‘m", "Kassa"]
    ws.append(head)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="EEF1F6")
    for i, r in enumerate(rows, 1):
        amount = money_text(r["sum"]) if i in TEXT_ROWS else r["sum"]
        ws.append([r["date"], r["name"], r["qty"], r["price"], amount, r["kassa"]])
        ws.cell(row=i + 1, column=1).number_format = "DD.MM.YYYY"
        ws.cell(row=i + 1, column=4).number_format = "# ##0"
        if i not in TEXT_ROWS:
            ws.cell(row=i + 1, column=5).number_format = "# ##0"
        else:
            ws.cell(row=i + 1, column=5).alignment = Alignment(horizontal="left")
    for col, w in zip("ABCDEF", [12, 24, 9, 13, 15, 10]):
        ws.column_dimensions[col].width = w
    wb.save(OUT / "savdo-oktabr.xlsx")

    with (OUT / "savdo-oktabr.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(head)
        for i, r in enumerate(rows, 1):
            w.writerow([r["date"].strftime("%d.%m.%Y"), r["name"], r["qty"], r["price"], money_text(r["sum"]) if i in TEXT_ROWS else r["sum"], r["kassa"]])

    text_lines = "\n".join(f"- {i + 1}-qator (jadvalda): {rows[i - 1]['date']:%d.%m.%Y}, {rows[i - 1]['name']}, «{money_text(rows[i - 1]['sum'])}» matn sifatida" for i in sorted(TEXT_ROWS))
    key = f"""# Javob kaliti: savdo-oktabr.xlsx

Instructor answer key for the formula-check demo (slide 28, 1:30).
Generated by `_build/make_formula_check.py`; do not edit by hand.

## The file

- 35 rows: 34 sales in October 2026 and 1 sale on 01.11.2026 (the last row).
- Three amounts were pasted as text, the way they arrive from Telegram (with spaces), so Excel's SUM skips them:
{text_lines}

## The numbers

| What | Total, so‘m |
| --- | --- |
| Correct October total (all 34 October rows, text amounts counted) | **{money_text(true_oct)}** |
| Excel `=SUM(E2:E36)` on the whole column (skips the 3 text cells, includes November) | {money_text(excel_sum_all)} |
| Excel SUM over October rows only (skips the 3 text cells) | {money_text(excel_sum_oct)} |
| All 35 rows with text amounts counted (wrongly includes November) | {money_text(true_oct + nov)} |
| The three text amounts together | {money_text(text_sum)} |
| The November row | {money_text(nov)} |

## How to run it

1. Upload `savdo-oktabr.xlsx` to Claude (or paste the CSV) and ask: «Oktabr oyidagi jami savdo qancha?»
2. Whatever number comes back, ask: «Qanday hisobladingiz? Formulani va qaysi qatorlarni qo‘shganingizni ko‘rsat.»
3. Compare with the table above.
   Possible slips: it adds the November row, or it skips the three text amounts, or it does both, and it gives the number with full confidence.
4. If the model gets it right, that is also a lesson: say so, then show that it only became checkable because you asked for the formula.
5. Closing line (UZ): «Excel xato qilsa, katakni qizil qiladi. AI xato qilsa, chiroyli javob beradi. Har doim so‘rang: formulangni ko‘rsat.»
"""
    (OUT / "javob-kaliti.md").write_text(key, encoding="utf-8")
    data = {"rows": [{"date": r["date"].strftime("%d.%m.%Y"), "name": r["name"], "qty": r["qty"], "price": r["price"],
                      "sum": r["sum"], "text": i in TEXT_ROWS, "nov": r["date"].month == 11, "kassa": r["kassa"]} for i, r in enumerate(rows, 1)],
            "totals": {"true_oct": true_oct, "excel_all": excel_sum_all, "excel_oct": excel_sum_oct, "all_incl_nov": true_oct + nov, "text_sum": text_sum, "nov": nov}}
    (OUT / "data.js").write_text("/* Generated by day-1/_build/make_formula_check.py. Do not edit. */\nwindow.FC_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
    print("October true total", money_text(true_oct), "| Excel SUM all", money_text(excel_sum_all), "| text", money_text(text_sum), "| Nov", money_text(nov))


if __name__ == "__main__":
    main()
